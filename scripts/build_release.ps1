$steamUtilsTestPath = Join-Path $pluginRootPath 'scripts\test_steam_utils.lua'
if (Test-Path -LiteralPath $steamUtilsTestPath -PathType Leaf) {
    $testDepsPath = Join-Path (Split-Path -Parent $pluginRootPath) '.test-deps'
    $oldPythonPath = $env:PYTHONPATH
    try {
        if (Test-Path -LiteralPath $testDepsPath -PathType Container) {
            $env:PYTHONPATH = $testDepsPath
        }
        $env:AKRAM_STEAM_UTILS_TEST = $steamUtilsTestPath
        & python -c "import os; from pathlib import Path; from lupa import LuaRuntime; p=Path(os.environ['AKRAM_STEAM_UTILS_TEST']); LuaRuntime(unpack_returned_tuples=True).execute(p.read_text(encoding='utf-8'))"
        if ($LASTEXITCODE -ne 0) { throw 'Steam utility tests failed.' }
    } finally {
        $env:PYTHONPATH = $oldPythonPath
        Remove-Item Env:AKRAM_STEAM_UTILS_TEST -ErrorAction SilentlyContinue
    }
}

$localeTestPath = Join-Path $pluginRootPath 'scripts\validate_locales.py'
if (Test-Path -LiteralPath $localeTestPath -PathType Leaf) {
    & python $localeTestPath
    if ($LASTEXITCODE -ne 0) { throw 'Locale validation failed.' }
}

$roundTrip = [IO.File]::ReadAllText($webkitPath, [Text.Encoding]::UTF8)
function Get-OrdinalOccurrenceCount([string]$Haystack, [string]$Needle) {
    if ([string]::IsNullOrEmpty($Needle)) { return 0 }
    $count = 0
    $offset = 0
    while (($index = $Haystack.IndexOf($Needle, $offset, [StringComparison]::Ordinal)) -ge 0) {
        $count += 1
        $offset = $index + $Needle.Length
    }
    return $count
}

if ((Get-OrdinalOccurrenceCount $roundTrip $public) -ne 1) {
    throw 'Generated WebKit bundle must contain the exact public UI source once.'
}
if ((Get-OrdinalOccurrenceCount $roundTrip $marker) -ne 1) {
    throw 'Generated WebKit bundle must contain one standalone UI marker.'
}

$wrapperIndex = $roundTrip.IndexOf('(() => {', [StringComparison]::Ordinal)
if ($wrapperIndex -lt 0) { throw 'Generated WebKit bundle has no standalone UI wrapper.' }
$prePublic = $roundTrip.Substring(0, $wrapperIndex)
foreach ($forbiddenToken in @('steam-db', 'RegisterForMessageFromParent', 'ExecutePluginModule')) {
    if ($prePublic.IndexOf($forbiddenToken, [StringComparison]::Ordinal) -ge 0) {
        throw "Foreign executable prefix found before LuaTools: $forbiddenToken"
    }
}

# The manifest covers every distributable file except itself and release ZIPs.
$manifestLines = Get-ChildItem -LiteralPath $pluginRootPath -Recurse -File |
    Where-Object {
        $_.FullName -ne $manifestPath -and
        $_.Extension -ne '.zip'
    } |
    ForEach-Object {
        $relativePath = $_.FullName.Substring($pluginRootPath.Length).TrimStart('\', '/').Replace('\', '/')
        [pscustomobject]@{
            RelativePath = $relativePath
            Line = "{0}  {1}" -f (Get-FileHash -Algorithm SHA256 -LiteralPath $_.FullName).Hash, $relativePath
        }
    } |
    Sort-Object RelativePath |
    Select-Object -ExpandProperty Line

[IO.File]::WriteAllText($manifestPath, (($manifestLines -join "`n") + "`n"), $encoding)

[pscustomobject]@{
    PluginRoot = $pluginRootPath
    Version = (Get-Content -Raw -LiteralPath $pluginJsonPath | ConvertFrom-Json).version
    WebkitSHA256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $webkitPath).Hash
    ManifestEntries = $manifestLines.Count
}
