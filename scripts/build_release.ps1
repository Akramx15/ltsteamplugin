param(
    [string]$PluginRoot = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
$pluginRootPath = [IO.Path]::GetFullPath($PluginRoot)
$publicPath = Join-Path $pluginRootPath 'public\luatools.js'
$webkitPath = Join-Path $pluginRootPath '.millennium\Dist\webkit.js'
$manifestPath = Join-Path $pluginRootPath 'SHA256-MANIFEST.txt'
$pluginJsonPath = Join-Path $pluginRootPath 'plugin.json'
$encoding = New-Object System.Text.UTF8Encoding($false)

foreach ($requiredPath in @($publicPath, $webkitPath, $pluginJsonPath)) {
    if (-not (Test-Path -LiteralPath $requiredPath -PathType Leaf)) {
        throw "Required file not found: $requiredPath"
    }
}

# Runtime lookups are keyed by the current AppID and manifests. Shipping a
# precomputed catalog of games would make the release stale and contradict the
# generic discovery contract.
foreach ($forbiddenCatalog in @(
    (Join-Path $pluginRootPath 'backend\temp_dl\all-appids.json'),
    (Join-Path $pluginRootPath 'backend\temp_dl\games.json')
)) {
    if (Test-Path -LiteralPath $forbiddenCatalog -PathType Leaf) {
        throw "Bundled static game catalog is forbidden: $forbiddenCatalog"
    }
}

# Steam's web views block the separately copied script, so emit one deterministic
# WebKit artifact containing only the standalone LuaTools UI.  Do not retain a
# generated plugin prefix here: an obsolete SteamDB prefix previously threw from
# RegisterForMessageFromParent and aborted full-document app-page navigations
# before LuaTools could start.
$public = [IO.File]::ReadAllText($publicPath, [Text.Encoding]::UTF8).TrimEnd("`r", "`n")
$marker = '/* Embedded standalone LuaTools UI. */'
$header = '/* LuaTools standalone WebKit entry; generated by scripts/build_release.ps1. */'
$rebuilt = $header + "`r`n" + $marker + "`r`n(() => {`r`n" + $public + "`r`n`r`n})();`r`n"
[IO.File]::WriteAllText($webkitPath, $rebuilt, $encoding)

# Fail the build on malformed plugin metadata or JavaScript. Locale JSON is
# validated below with Python because PowerShell treats differently-cased JSON
# keys as duplicates even though JSON object names are case-sensitive.
Get-Content -Raw -LiteralPath $pluginJsonPath | ConvertFrom-Json | Out-Null

& node --check $publicPath
if ($LASTEXITCODE -ne 0) { throw 'public/luatools.js failed node --check.' }
& node --check $webkitPath
if ($LASTEXITCODE -ne 0) { throw '.millennium/Dist/webkit.js failed node --check.' }

$indexPath = Join-Path $pluginRootPath '.millennium\Dist\index.js'
if (Test-Path -LiteralPath $indexPath -PathType Leaf) {
    & node --check $indexPath
    if ($LASTEXITCODE -ne 0) { throw '.millennium/Dist/index.js failed node --check.' }
}

$bootstrapTestPath = Join-Path $pluginRootPath 'scripts\test_webkit_bootstrap.js'
if (Test-Path -LiteralPath $bootstrapTestPath -PathType Leaf) {
    & node $bootstrapTestPath
    if ($LASTEXITCODE -ne 0) { throw 'WebKit bootstrap tests failed.' }
}

